"""Make-BytePatches-202.py - 2.0.2 "Team Racing" byte-patch table (developer tool).

Same engine as Make-BytePatches.py but the 2.0.2 file set. Compares the OEM files
from the extracted 2.0.2 disc with the patched copies in a working 2.0.2 install and
writes Patches\\nascar-202-bytepatches.txt. Only same-size patches (verify-then-overwrite,
no Python on the player's PC).

NASCAR_Selection.am is deliberately NOT here: its only edit is the MusicDir absolute
path, which depends on the install location and is applied separately (menu music is a
beta.2 item). The dongle image and the mode-limit are done at runtime by the shim.

Usage: python -I Make-BytePatches-202.py <payload File_Group> <working install> <out file>
"""
import os
import sys

FILES = [
    r"Shell\bin\plugins\NASCARPlugIn.dll",   # timezone S->G, CD check D:->?:, operator Receive(0), WAN off, nightly-restart check off
    r"Shell\bin\Dongle.dll",                 # image NASCAR2.0CTRYXX_CAB0 (fixed, same-size)
    r"Shell\bin\plugins\HerculesPlugIn.dll", # coin-monitor wait (if patched)
    r"Shell\Shell.am",                       # nvcpl Gvr.Launch mode 0 -> 2 (x2); 15 s IO-board wait -> 0.5 s
    r"Shell\NASCAR_Attract.am",              # CabinetComm receivedPacket && guard
]
MERGE_GAP = 8


def find(root, rel):
    cur = root
    for part in rel.split("\\"):
        hit = [e for e in os.listdir(cur) if e.lower() == part.lower()]
        if not hit:
            raise FileNotFoundError(os.path.join(cur, part))
        cur = os.path.join(cur, hit[0])
    return cur


def runs(a, b):
    out, i, n = [], 0, len(a)
    while i < n:
        if a[i] != b[i]:
            s = i
            while i < n and a[i] != b[i]:
                i += 1
            if out and s - out[-1][1] <= MERGE_GAP:
                out[-1][1] = i
            else:
                out.append([s, i])
        else:
            i += 1
    return out


def main():
    payload, install, out = sys.argv[1:4]
    lines = ["# NASCAR Team Racing 2.0.2 byte patches - generated by Tools\\Make-BytePatches-202.py, do not edit.",
             "# file <install-relative path> / <hex offset> <OEM hex> <patched hex>"]
    for rel in FILES:
        try:
            oem = open(find(os.path.join(payload, "NASCAR"), rel), "rb").read()
            new = open(find(install, rel), "rb").read()
        except FileNotFoundError as e:
            sys.exit("missing: " + str(e))
        if len(oem) != len(new):
            sys.exit("size differs, not a byte patch: " + rel)
        r = runs(oem, new)
        lines.append("file " + rel)
        for s, e in r:
            lines.append("%x %s %s" % (s, oem[s:e].hex(), new[s:e].hex()))
        print("%-45s %3d patch(es), %6d bytes" % (rel, len(r), sum(e - s for s, e in r)))
    with open(out, "w", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("-> " + out)


if __name__ == "__main__":
    main()
